const assert = require("node:assert/strict");
const fs = require("node:fs");
const vm = require("node:vm");
const link = {hidden: true, removeAttribute(name) {delete this[name]}};
const reader = {document: {getElementById() {return link}, addEventListener() {}}};
vm.createContext(reader);
vm.runInContext(fs.readFileSync("js/parshadata7.js", "utf8"), reader);
vm.runInContext(fs.readFileSync("js/shafeh-reading.js", "utf8"), reader);
reader.getSeferFromParasha = parsha => Object.keys(reader.parshios).find(book => reader.parshios[book].includes(parsha));
reader.currView = "text";
reader.currParsha = "וירא";
reader.currAliya = 1;
reader.updateShafehReadingLink();
assert.equal(link.href, "https://shafeh.org/chumash/reading/bereishis/18/1/18/14");
assert.equal(link.hidden, false);
reader.currAliya = 2;
reader.updateShafehReadingLink();
assert.equal(link.href, "https://shafeh.org/chumash/reading/bereishis/18/15/18/33");
reader.currParsha = "מטות-מסעי";
reader.currAliya = 7;
reader.updateShafehReadingLink();
assert.equal(link.href, "https://shafeh.org/chumash/reading/bamidbar/35/9/36/13");
reader.currView = "aliyos";
reader.updateShafehReadingLink();
assert.equal(link.hidden, true);
assert.equal(link.href, undefined);
assert.equal(reader.shafehReadingUrl("unknown", "1:1 1:2"), null);
assert.equal(reader.shafehReadingUrl("בראשית", "1:1 1:2?name=private"), null);
console.log("Selected reading handoff tests passed");
